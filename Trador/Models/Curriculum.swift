import SwiftUI

private func card(_ icon: String, _ title: String, _ text: String, example: String? = nil, visual: LessonVisual? = nil) -> LessonCard {
    LessonCard(icon: icon, title: title, text: text, example: example, visual: visual)
}

private func q(_ prompt: String, _ options: [String], _ answer: Int, _ explanation: String) -> QuizQuestion {
    QuizQuestion(prompt: prompt, options: options, answer: answer, explanation: explanation)
}

